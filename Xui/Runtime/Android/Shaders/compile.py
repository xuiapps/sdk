"""Compile the source generator's HLSL to validated SPIR-V at APK build time.

Shader identity is SHA-256 of the exact UTF-8 source, shared with VulkanDevice.
No runtime compiler or hand-maintained copy of an application's shader is needed.
"""
import hashlib
import pathlib
import re
import subprocess
import sys

sources, output, compiler = map(pathlib.Path, sys.argv[1:])
output.mkdir(parents=True, exist_ok=True)
expected = set()
for generated in sources.rglob('*.g.cs'):
    text = generated.read_text(encoding='utf-8-sig')
    if 'Generated by Xui.CompileTime' not in text:
        continue
    match = re.search(r'private const string HlslSource = @"((?:""|[^"])*)";', text)
    if not match:
        raise RuntimeError(f'Missing generated HLSL in {generated}')
    source = match.group(1).replace('""', '"')
    key = hashlib.sha256(source.encode('utf-8')).hexdigest()
    for stage, entry in [('vertex', 'VSMain'), ('fragment', 'PSMain')]:
        name = f'{key}.{entry}.spv'
        expected.add(name)
        target = output / name
        # Include compiler and script changes in incremental rebuild decisions.
        if target.exists() and target.stat().st_mtime >= max(generated.stat().st_mtime, compiler.stat().st_mtime, pathlib.Path(__file__).stat().st_mtime):
            continue
        subprocess.run([str(compiler), '-x', 'hlsl', '-fshader-stage='+stage,
                        '-fentry-point='+entry, '-fauto-map-locations', '-finvert-y',
                        '--target-env=vulkan1.0', '-O', '-o', str(target), '-'],
                       input=('#pragma pack_matrix(row_major)\n'+source).encode('utf-8'), check=True)
        subprocess.run([str(compiler.with_name('spirv-val')), '--target-env', 'vulkan1.0', str(target)], check=True)
        print(f'Xui Vulkan: {generated.name} → {name}')
for stale in output.glob('*.spv'):
    if stale.name not in expected:
        stale.unlink()
if not expected:
    raise RuntimeError('No Xui generated shaders found; check EmitCompilerGeneratedFiles')
